import { test, expect, openGame, gameState } from './fixtures.js';
import { expectVisibility, fits, preference, quietCup } from './onScreenControls.js';

test('mobile Auto, Show and Hide persist independently of Touch and View', async ({ page, problems }) => {
  await page.setViewportSize({ width: 375, height: 667 });
  await openGame(page);
  await expectVisibility(page, true, '.controls-easy');
  const settings = await page.evaluate(() => window.__TEACUP__.settings());
  await quietCup(page);
  await preference(page, 'hide');
  await expectVisibility(page, false);
  await fits(page);
  await page.reload();
  await expectVisibility(page, false);
  expect(await page.evaluate(() => window.__TEACUP__.settings())).toEqual(settings);
  await page.locator('#menuBtn').click();
  await page.getByText('Controls & Settings', { exact: true }).click();
  await expect(page.locator('#activeControls')).toContainText('Use a keyboard');
  await expect(page.locator('#onScreenControlsHelp')).toContainText('keyboard');
  await page.locator('#breakControlsBtn').click();
  await expect(page.locator('#overlayTouchSummary')).toContainText('On-screen controls hidden');
  await expect(page.locator('#overlayTouchText')).toContainText('cup gestures still work');
  await page.keyboard.press('Escape');
  await expect(page.locator('#breakControlsBtn')).toBeFocused();
  await page.locator('#closeBreak').click();
  await preference(page, 'show');
  await expectVisibility(page, true, '.controls-easy');
  await page.locator('#viewBtn').click();
  await expect(page.locator('body')).toHaveAttribute('data-view', 'full');
  await quietCup(page);
  await fits(page);
  await preference(page, 'auto');
  await expectVisibility(page, true, '.controls-easy');
  await page.setViewportSize({ width: 844, height: 390 });
  await fits(page);
  await preference(page, 'hide');
  await expectVisibility(page, false);
  await fits(page);
  await preference(page, 'show');
  await fits(page);
  expect(problems).toEqual([]);
});

test('mobile Auto retains real touch steering and Easy Touch cup gestures', async ({ page, problems }) => {
  await page.setViewportSize({ width: 375, height: 667 });
  await openGame(page);
  await quietCup(page);
  await expectVisibility(page, true, '.controls-easy');
  const start = await gameState(page);
  const cdp = await page.context().newCDPSession(page);
  const pad = await page.locator('.controls-easy [data-hold="right"]').boundingBox();
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: pad.x + pad.width / 2, y: pad.y + pad.height / 2 }] });
  await expect.poll(async () => (await gameState(page)).angle).not.toBe(start.angle);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  const angle = (await gameState(page)).angle;
  await page.waitForTimeout(150);
  expect((await gameState(page)).angle).toBe(angle);
  const cup = await page.locator('#game').boundingBox();
  const point = { x: cup.x + cup.width / 2, y: cup.y + cup.height / 2 };
  await page.touchscreen.tap(point.x, point.y); await page.touchscreen.tap(point.x, point.y);
  await expect.poll(async () => (await gameState(page)).milkLeft).toBe(start.milkLeft - 1);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] });
  await expect.poll(async () => (await gameState(page)).sugarLeft).toBe(start.sugarLeft - 1);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await cdp.detach();
  await preference(page, 'hide');
  await expectVisibility(page, false);
  expect(await page.evaluate(() => window.__TEACUP__.settings())).toEqual({ touch: 'easy', autoSteam: true });
  await fits(page);
  expect(problems).toEqual([]);
});
